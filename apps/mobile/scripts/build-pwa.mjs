// Builds the installable web app (PWA) into dist/: Expo web export, then
// iOS home-screen tags, a precaching service worker and security headers.
import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const dist = join(root, 'dist');

execSync('npx expo export --platform web --output-dir dist', { cwd: root, stdio: 'inherit', env: { ...process.env, CI: '1' } });

// 1. Home-screen / standalone tags.
const indexPath = join(dist, 'index.html');
let html = readFileSync(indexPath, 'utf8');
html = html
  .replace(/<meta name="viewport"[^>]*>/, '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />')
  .replace(/<meta httpEquiv="X-UA-Compatible"[^>]*>\s*/, '')
  .replace(
    '</head>',
    [
      '<meta name="color-scheme" content="dark light" />',
      '<meta name="theme-color" content="#08080A" media="(prefers-color-scheme: dark)" />',
      '<meta name="theme-color" content="#F3F3F6" media="(prefers-color-scheme: light)" />',
      '<meta name="apple-mobile-web-app-capable" content="yes" />',
      '<meta name="mobile-web-app-capable" content="yes" />',
      '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />',
      '<meta name="apple-mobile-web-app-title" content="Budgi" />',
      '<meta name="format-detection" content="telephone=no" />',
      '<link rel="apple-touch-icon" href="/apple-touch-icon.png" />',
      '<link rel="manifest" href="/manifest.webmanifest" />',
      // No white flash before React mounts.
      '<style>html,body{background:#08080A}@media (prefers-color-scheme: light){html,body{background:#F3F3F6}}</style>',
      '<script src="/register-sw.js" defer></script>',
      '</head>',
    ].join('\n    '),
  );
writeFileSync(indexPath, html);

// 2. Service worker with a precache list and a content hash as its version.
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push('/' + relative(dist, p).split('\\').join('/'));
  }
};
walk(dist);
const precache = files.filter((f) => !/^\/(_headers|sw\.js|metadata\.json|connected\.html)$/.test(f) && !f.endsWith('.map'));
const hash = createHash('sha256');
for (const f of precache) hash.update(f).update(readFileSync(join(dist, f)));
const version = hash.digest('hex').slice(0, 12);

writeFileSync(
  join(dist, 'sw.js'),
  `// Generated by scripts/build-pwa.mjs
const CACHE = 'budgi-${version}';
const PRECACHE = ${JSON.stringify(['/', ...precache.filter((f) => f !== '/index.html')])};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  // Never cache API traffic (financial data, signed requests).
  if (event.request.method !== 'GET' || url.origin !== location.origin || /^\\/(v1|plaid)\\//.test(url.pathname) || url.pathname === '/health') return;
  if (event.request.mode === 'navigate') {
    // Network first so updates land; fall back to the cached app offline.
    event.respondWith(fetch(event.request).catch(() => caches.match('/')));
    return;
  }
  event.respondWith(caches.match(event.request).then((hit) => hit || fetch(event.request)));
});
`,
);
console.log(`PWA built: ${precache.length} files precached (version ${version}).`);
